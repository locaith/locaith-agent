// Sinh webview/src/styles/fonts.css từ các gói @fontsource.
//   node scripts/gen-fonts-css.mjs
//
// - Chỉ dùng woff2 (bỏ woff) và 3 subset cần cho tiếng Việt: latin, latin-ext, vietnamese.
// - `unicode-range` được sao nguyên từ CSS của fontsource để trình duyệt chỉ tải subset nào thật sự dùng tới.
// - url() trỏ thẳng vào node_modules; esbuild (loader `file`) sẽ chép font sang dist/webview/assets.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outFile = path.join(root, 'webview', 'src', 'styles', 'fonts.css');

const SUBSETS = ['vietnamese', 'latin-ext', 'latin']; // thứ tự khai báo: subset cụ thể trước
const FAMILIES = [
  { pkg: 'be-vietnam-pro', name: 'Be Vietnam Pro', normal: [400, 500, 600, 700], italic: [400] },
  { pkg: 'manrope', name: 'Manrope', normal: [400, 500, 600, 700, 800], italic: [] },
  { pkg: 'inter', name: 'Inter', normal: [400, 500, 600, 700], italic: [400] },
  { pkg: 'jetbrains-mono', name: 'JetBrains Mono', normal: [400, 500, 700], italic: [400] },
];

const out = [
  '/* GENERATED by scripts/gen-fonts-css.mjs - do not edit by hand. */',
  '/* Self-hosted fonts: the webview CSP forbids loading fonts from the network. */',
  '',
];
let blocks = 0;

for (const fam of FAMILIES) {
  const variants = [
    ...fam.normal.map((w) => ({ weight: w, style: 'normal', file: `${w}.css` })),
    ...fam.italic.map((w) => ({ weight: w, style: 'italic', file: `${w}-italic.css` })),
  ];
  out.push(`/* ${fam.name} */`);
  for (const v of variants) {
    const cssPath = path.join(root, 'node_modules', '@fontsource', fam.pkg, v.file);
    const css = await readFile(cssPath, 'utf8');
    const found = new Map();
    for (const m of css.matchAll(/\/\*\s*([\w-]+)\s*\*\/\s*@font-face\s*\{([^}]*)\}/g)) {
      const body = m[2];
      const subset = m[1].replace(`${fam.pkg}-`, '').replace(/-\d{3}-(normal|italic)$/, '');
      if (!SUBSETS.includes(subset)) continue;
      const range = /unicode-range:\s*([^;]+);/.exec(body)?.[1]?.trim();
      const fileName = /url\(\.\/files\/([^)]+?\.woff2)\)/.exec(body)?.[1];
      if (!range || !fileName) throw new Error(`Không đọc được ${fam.pkg} ${v.file} (${subset})`);
      found.set(subset, { range, fileName });
    }
    for (const subset of SUBSETS) {
      const f = found.get(subset);
      if (!f) throw new Error(`Thiếu subset ${subset} trong ${fam.pkg}/${v.file}`);
      out.push(
        '@font-face {',
        `  font-family: '${fam.name}';`,
        `  font-style: ${v.style};`,
        `  font-weight: ${v.weight};`,
        '  font-display: swap;',
        `  src: url(../../../node_modules/@fontsource/${fam.pkg}/files/${f.fileName}) format('woff2');`,
        `  unicode-range: ${f.range};`,
        '}',
      );
      blocks++;
    }
  }
  out.push('');
}

await mkdir(path.dirname(outFile), { recursive: true });
await writeFile(outFile, out.join('\n'), 'utf8');
console.log(`Đã ghi ${path.relative(root, outFile)} (${blocks} khối @font-face)`);
