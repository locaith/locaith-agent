const dictionaries: Record<Lang, Record<string, string>> = { vi, en };

function interpolate(template: string, params?: Record<string, string | number>): string {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (m, k: string) => (k in params ? String(params[k]) : m));
}

export function t(lang: Lang, key: I18nKey, params?: Record<string, string | number>): string {
  return interpolate(dictionaries[lang][key] ?? dictionaries.vi[key] ?? key, params);
}

/** Tra khóa động (ví dụ `tool.${name}.run`); không có khóa → undefined để gọi nơi quyết định phương án dự phòng. */
export function tOpt(lang: Lang, key: string, params?: Record<string, string | number>): string | undefined {
  const template = dictionaries[lang][key] ?? dictionaries.vi[key];
  return template === undefined ? undefined : interpolate(template, params);
}

export type TFn = (key: I18nKey, params?: Record<string, string | number>) => string;

export function makeT(lang: Lang): TFn {
  return (key, params) => t(lang, key, params);
}
