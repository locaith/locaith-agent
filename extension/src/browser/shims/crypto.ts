/**
 * Thay `node:crypto` trong bản trình duyệt: chỉ cần `createHash('sha1' | 'sha256').update(chuỗi).digest('hex')`, ĐỒNG BỘ.
 * Web Crypto (`crypto.subtle.digest`) bất đồng bộ nên không dùng được cho các chỗ băm đồng bộ của engine (dấu vân tay prompt,
 * băm nội dung tệp). Các hàm băm đây chỉ dùng để nhận diện thay đổi — không phải bảo mật.
 */

const enc = new TextEncoder();

function toBytes(input: string | Uint8Array): Uint8Array {
  return typeof input === 'string' ? enc.encode(input) : input;
}

function hex(words: number[]): string {
  return words.map((w) => (w >>> 0).toString(16).padStart(8, '0')).join('');
}

/** Đệm theo chuẩn MD: bit 1, các bit 0, rồi độ dài (bit) 64-bit big-endian. */
function pad(bytes: Uint8Array): Uint8Array {
  const bitLen = bytes.length * 8;
  const total = (((bytes.length + 8) >> 6) + 1) << 6;
  const out = new Uint8Array(total);
  out.set(bytes);
  out[bytes.length] = 0x80;
  const dv = new DataView(out.buffer);
  dv.setUint32(total - 8, Math.floor(bitLen / 0x100000000), false);
  dv.setUint32(total - 4, bitLen >>> 0, false);
  return out;
}

const rotl = (x: number, n: number) => (x << n) | (x >>> (32 - n));
const rotr = (x: number, n: number) => (x >>> n) | (x << (32 - n));

export function sha1Hex(input: string | Uint8Array): string {
  const data = pad(toBytes(input));
  const dv = new DataView(data.buffer);
  let h0 = 0x67452301;
  let h1 = 0xefcdab89;
  let h2 = 0x98badcfe;
  let h3 = 0x10325476;
  let h4 = 0xc3d2e1f0;
  const w = new Array<number>(80);
  for (let off = 0; off < data.length; off += 64) {
    for (let i = 0; i < 16; i++) w[i] = dv.getUint32(off + i * 4, false);
    for (let i = 16; i < 80; i++) w[i] = rotl(w[i - 3] ^ w[i - 8] ^ w[i - 14] ^ w[i - 16], 1);
    let a = h0;
    let b = h1;
    let c = h2;
    let d = h3;
    let e = h4;
    for (let i = 0; i < 80; i++) {
      let f: number;
      let k: number;
      if (i < 20) {
        f = (b & c) | (~b & d);
        k = 0x5a827999;
      } else if (i < 40) {
        f = b ^ c ^ d;
        k = 0x6ed9eba1;
      } else if (i < 60) {
        f = (b & c) | (b & d) | (c & d);
        k = 0x8f1bbcdc;
      } else {
        f = b ^ c ^ d;
        k = 0xca62c1d6;
      }
      const t = (rotl(a, 5) + f + e + k + w[i]) | 0;
      e = d;
      d = c;
      c = rotl(b, 30);
      b = a;
      a = t;
    }
    h0 = (h0 + a) | 0;
    h1 = (h1 + b) | 0;
    h2 = (h2 + c) | 0;
    h3 = (h3 + d) | 0;
    h4 = (h4 + e) | 0;
  }
  return hex([h0, h1, h2, h3, h4]);
}

